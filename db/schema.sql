-- ЛР9 · Схема базы данных
-- Тема: Система обработки обращений жильцов общежития
-- Соответствие модели: docs/data-model.md (Ticket / Room / User)
-- Имена таблиц и столбцов совпадают с конфигурацией AppDbContext (ЛР10):
-- rooms / users / tickets, snake_case, CHECK статусов, RESTRICT у внешних ключей.
--
-- Повторный запуск: скрипт сначала удаляет учебные таблицы и создаёт их заново.
-- Пересоздание схемы — только для учебной базы, в приложении DELETE не используется.

DROP TABLE IF EXISTS tickets CASCADE;
DROP TABLE IF EXISTS users CASCADE;
DROP TABLE IF EXISTS rooms CASCADE;

-- Справочник комнат (термин курса — Site, в теме — Комната)
CREATE TABLE rooms (
  id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name  varchar(50) NOT NULL
);

-- Пользователи: создатель и исполнитель обращений.
-- password_hash — хэш ASP.NET Identity (PBKDF2), не исходный пароль (ЛР11).
CREATE TABLE users (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          varchar(100) NOT NULL,
  login         varchar(50)  NOT NULL,
  role          varchar(30)  NOT NULL,
  password_hash varchar(200) NOT NULL
);

-- Главная сущность — обращение жильца.
-- Название комнаты хранится только в rooms, в обращении — внешний ключ room_id (3НФ из ЛР2).
CREATE TABLE tickets (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  number            varchar(20)  NOT NULL,
  title             varchar(80)  NOT NULL,
  description       varchar(500) NOT NULL,
  status            varchar(20)  NOT NULL,
  room_id           integer      NOT NULL,
  created_at        timestamptz  NOT NULL,
  created_by_user_id integer     NOT NULL,
  assignee_user_id  integer      NULL, -- у нового обращения исполнителя нет
  CONSTRAINT tickets_number_unique UNIQUE (number),
  CONSTRAINT tickets_status_check
    CHECK (status IN ('New', 'InProgress', 'Closed', 'Cancelled')),
  CONSTRAINT fk_tickets_room
    FOREIGN KEY (room_id) REFERENCES rooms (id) ON DELETE RESTRICT,
  CONSTRAINT fk_tickets_creator
    FOREIGN KEY (created_by_user_id) REFERENCES users (id) ON DELETE RESTRICT,
  CONSTRAINT fk_tickets_assignee
    FOREIGN KEY (assignee_user_id) REFERENCES users (id) ON DELETE RESTRICT
);

-- Обязательные индексы из методички ЛР9

-- зачем: фильтр списка обращений по статусу (GET /api/tickets, запрос 1)
CREATE INDEX tickets_status_idx ON tickets (status);

-- зачем: JOIN со справочником комнат и выборка по комнате
CREATE INDEX tickets_room_id_idx ON tickets (room_id);

-- зачем: список «моих обращений» для исполнителя (фильтр по assignee_user_id)
CREATE INDEX tickets_assignee_user_id_idx ON tickets (assignee_user_id);

