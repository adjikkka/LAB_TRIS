-- ЛР9 · Обязательные запросы
-- Порядок чтения SELECT: из какой таблицы → с чем соединить → условие →
-- группировка/сортировка → какие столбцы показать.
-- Выполнять после db/schema.sql и db/seed.sql.

-- ============================================================
-- 1. Фильтр и сортировка: новые обращения, свежие сверху.
-- Ускоряется индексом tickets_status_idx.
-- ============================================================
SELECT number, title, status, created_at
FROM tickets
WHERE status = 'New'
ORDER BY created_at DESC;

-- Ожидание: две строки — ОБР-2026-005 и ОБР-2026-001.

-- ============================================================
-- 2. JOIN: название комнаты из справочника, а не только room_id.
-- Требование методички: JOIN обязан показывать имя справочника.
-- ============================================================
SELECT t.number, t.title, r.name AS room_name, t.status
FROM tickets AS t
JOIN rooms AS r ON r.id = t.room_id
ORDER BY t.created_at DESC;

-- Ожидание: семь строк с названиями «Комната 305», «Комната 203» и т. д.

-- ============================================================
-- 3. GROUP BY с агрегатом: сколько обращений в каждом статусе.
-- Seed позволяет увидеть все четыре группы.
-- Сводка полезна коменданту (роль «руководитель» из ЛР1).
-- ============================================================
SELECT status, COUNT(*) AS count
FROM tickets
GROUP BY status
ORDER BY status;

-- Ожидание: Cancelled 1, Closed 2, InProgress 2, New 2.

-- ============================================================
-- 4. JOIN + GROUP BY: загрузка исполнителей.
-- Кто и сколько обращений ведёт — статистика для коменданта.
-- ============================================================
SELECT u.name AS executor_name, COUNT(t.id) AS tickets_count
FROM users AS u
LEFT JOIN tickets AS t ON t.assignee_user_id = u.id
GROUP BY u.name
ORDER BY tickets_count DESC, u.name;

-- Ожидание: сантехник — 2, электрик — 2, комендант — 0 (LEFT JOIN).

-- ============================================================
-- 5. Дополнительно: обращения без исполнителя (NULL — «нет значения»,
-- не ноль и не пустая строка). Их видит комендант и назначает исполнителя.
-- ============================================================
SELECT number, title, room_id, created_at
FROM tickets
WHERE assignee_user_id IS NULL
ORDER BY created_at;

-- Ожидание: ОБР-2026-004 (отменено), ОБР-2026-001, ОБР-2026-005.
